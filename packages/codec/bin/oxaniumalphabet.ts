/**
 * Regenerate `src/oxaniumalphabet.ts`, our own letters' alphabet as data, so reading a configuration needs no
 * font, a fix to `todo.md` 7.3.5.
 *
 * ```
 * node packages/codec/bin/oxaniumalphabet.ts            check the module against the font
 * node packages/codec/bin/oxaniumalphabet.ts --write    rewrite src/oxaniumalphabet.ts
 * ```
 *
 * **Why the alphabet is generated rather than drawn where it is read.** `characterMap` tries every alphabet on
 * every configuration, so a reader that names a device asks for ours even on a Logitech compile, and drawing
 * it needs Oxanium's files, which since 7.3.5 only the Node entry supplies. The alphabet is a function of the
 * font and of `lettering.ts`'s faces alone, so it is computed here once, `oxaniumAlphabetFromFont`, and
 * written as `packOxaniumAlphabet` encodes it. Run this with `--write` after any change to the faces, the
 * weights, the characters or the way a form or a structure is read; `test/oxaniumalphabet.test.ts` fails until
 * then.
 *
 * The check compares the decoded tables and not the text, because the text is Node's deflate of them and a
 * different zlib may write the same tables in other bytes.
 */
import { writeFileSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { deflateSync } from 'node:zlib';
import '../src/resources.node.ts';
import { oxaniumAlphabet, oxaniumAlphabetFromFont, packOxaniumAlphabet } from '../src/text.ts';

const OUT = new URL('../src/oxaniumalphabet.ts', import.meta.url);

/** The base64 is cut into lines this wide, so the file opens in an editor and a change shows as lines. */
const LINE = 112;

const alphabet = oxaniumAlphabetFromFont();
const packed = packOxaniumAlphabet(alphabet, (bytes) => new Uint8Array(deflateSync(bytes, { level: 9 })));
const lines: string[] = [];
for (let k = 0; k < packed.length; k += LINE) lines.push(`  '${packed.slice(k, k + LINE)}',`);

const text = `/**
 * GENERATED by \`node packages/codec/bin/oxaniumalphabet.ts --write\`. Do not edit.
 *
 * Our own letters' alphabet, \`oxaniumAlphabet\` in \`text.ts\`: per form and per structure the characters it
 * draws, and per form the faces and weights that draw it, computed from Oxanium by \`oxaniumAlphabetFromFont\`
 * so a configuration is read with no font supplied. The tables' JSON deflated and in base64,
 * \`packOxaniumAlphabet\`, since as JSON they are 4.2 MB. \`test/oxaniumalphabet.test.ts\` holds this to the font.
 */
export const OXANIUM_ALPHABET_TABLES: string = [
${lines.join('\n')}
].join('');
`;

const count = (table: Readonly<Record<string, unknown>> | undefined): number => Object.keys(table ?? {}).length;
console.log(`${count(alphabet.forms)} forms, ${count(alphabet.structures)} structures, ${count(alphabet.drawnIn)} forms with their faces`);
console.log(`${packed.length} characters of base64 in ${lines.length} lines`);

if (process.argv.includes('--write')) {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT.pathname}`);
} else {
  // The module as this process loaded it, through the reader's own door: what `characterMap` reads.
  const tables = (() => {
    try {
      return oxaniumAlphabet();
    } catch {
      // A module that does not decode, the empty one a fresh table starts from among them, differs.
      return undefined;
    }
  })();
  console.log(isDeepStrictEqual(tables, alphabet) ? 'src/oxaniumalphabet.ts is up to date' : 'src/oxaniumalphabet.ts DIFFERS, rerun with --write');
}
