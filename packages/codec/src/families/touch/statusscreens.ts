/**
 * The Harmony One's status screens built whole from a description: `todo-compile-one.md` 4.5, findings section
 * 413, through the template engine of sections 411 and 412, `screentemplate.ts`.
 *
 * **What they are.** The head of a Harmony One configuration's mode table holds one screen per status code, thirty,
 * at modes 10 to 39, and the event map (base slot 4) names them, key `n` to mode `10 + n` on all nineteen compiles.
 * Section 408 read the firmware: it walks the configuration's event map for code 9 alone, "LCD Module Failed",
 * which `fixedscreens.ts` builds (section 411), and raises no other code with the configuration's verdict
 * standing, so the other twenty nine are drawn by nothing as read. They are carried anyway because every compile of
 * Logitech's carries them and nobody has run a Harmony One configuration without them; this module builds them so that a
 * configuration of ours can carry them too. **Leaving them out** (a head 29 modes shorter and the event map
 * renumbered) is the other branch of 4.5 and needs a remote to say whether it accepts that: section 413.
 *
 * **One shape, thirty texts.** Every status screen is code 9's shape, measured on the sixteen English compiles
 * of skin 54 and both European ones: its own key map swallows the page arrows, starts a timer on entering and
 * cancels it on leaving, and binds the header handler's three base slot 11 programs; it has one page, whose list
 * is empty; its chrome is section 411's, titled "System Message: N" with N the code; and its page draws, in the
 * body font, one to four lines centred on the screen. What differs between the thirty is the code in the title
 * and the lines, `STATUS_LINES`, which are Logitech's words for each code: the same words the status container
 * at external `0x002000` draws (section 244) for 29 of the 30, code 28 being "USB CONNECTED" in capitals there,
 * which is a reading aid and nothing this module reads.
 *
 * **Where text goes**: the title at 6, 4 (section 411's chrome); each line centred on the 176 pixel width rounded
 * down, `floor((176 - w) / 2)`, section 409's rule; and the lines twelve apart in a block centred on y 168, so n
 * lines start at `174 - 6n`: 168 for one line, 162 for two, 156 for three and 150 for four, on every one of the
 * thirty and on the Dutch compile's thirty too. Code 9's "LCD Module" and "Failed" at 162 and 174 are the case
 * section 411 measured, and are generated by the same rule now.
 *
 * **What the description carries**: the mode each screen is (the event map's value for its code), its hit page,
 * the full screen picture its chrome draws, the timer, the base slot 11 programs, the two lists each screen names
 * (its header handler's and its chrome's), the two fonts, and the homes of texts drawn by reference to a copy
 * outside these screens. **What is generated**: every opcode and constant operand, the tags and their order, both
 * lists' instructions, every word and its place, which text is inline (the first in mode order, `screentemplate.ts`'
 * rule), the entry's flag and the records' bytes.
 *
 * **What is not built**: the event map itself, which names these screens by mode and is the wiring's (section
 * 410), and code 9's screen, which is `fixedscreens.ts`'. The lists these screens name call no list of their own.
 *
 * English only; skin 54, and the European skin 59, whose status screens are skin 54's word for word. The Harmony
 * One alone, the touch family's; the Harmony 600, 650 and 700 are the four slot family, whose configurations of
 * ours leave the status screens out (section 405's correction), and are not built here. Read only towards hardware: the result is pieces.
 */
