/** The status codes a configuration holds a screen for, 0 to 29, every key of the event map on all nineteen compiles. */
export const STATUS_CODES: readonly number[] = STATUS_LINES.map((_, code) => code);

/** The y the lines of a status screen are centred on, and how far apart they are. */
const BLOCK_CENTRE = 168;
const LINE_PITCH = 12;

/**
 * A status screen as a template, for the code given, in the font roles the caller names: the shape every one of
 * the thirty has, code 9's included, which `fixedscreens.ts` builds through this so that the shape is stated once.
 * Its lines are `STATUS_LINES`' for the code, centred on the screen in a block centred on y 168.
 */
export function statusScreen<F extends string>(code: number, fonts: { title: F; body: F }): TemplateScreen<F> {
  const rows = STATUS_LINES[code];
  if (rows === undefined) throw new ScreenRecordError(`there is no status code ${code}`);
  // n lines twelve apart centred on 168: the first at 168 - 6 (n - 1), which is 174 - 6n.
  const top = BLOCK_CENTRE - (LINE_PITCH / 2) * (rows.length - 1);
  const parts: Part<F>[] = [{ op: 'chrome' }, font(fonts.body), ...rows.map((row, r) => centred(row, top + LINE_PITCH * r))];
  return {
    name: `Status ${code}`,
    own: [...ARROWS, [TAG_ENTER, TIMER_START], [TAG_LEAVE, TIMER_CANCEL], [TAG_HEADER, HEADER]],
    // The chrome's count font is never selected on a screen of one page, so the title role stands in for it.
    chrome: chrome<F>(`System Message: ${code}`, 1, { title: fonts.title, count: fonts.title }),
    pages: [{ list: [], parts }],
  };
}

/** The fonts these screens select: the chrome's title and the lines'. */
export type StatusScreenFont = 'title' | 'body';
export const STATUS_SCREEN_FONTS: readonly StatusScreenFont[] = ['title', 'body'];

/** The codes this module builds, every code but the display test's, in code order. */
const BUILT_CODES: readonly number[] = STATUS_CODES.filter((code) => code !== DISPLAY_TEST_CODE);

const SCREENS: readonly TemplateScreen<StatusScreenFont>[] = BUILT_CODES.map((code) => statusScreen<StatusScreenFont>(code, { title: 'title', body: 'body' }));

/** The screens' names, in the order a description lists them, which is code order. */
export const TOUCH_STATUS_SCREENS: readonly string[] = SCREENS.map((one) => one.name);

/** The twenty nine as templates, in code order, for a configuration numbered from nothing, `numbering.ts`. */
export const TOUCH_STATUS_TEMPLATES: readonly TemplateScreen<StatusScreenFont>[] = SCREENS;

// ---------------------------------------------------------------------------------------------------------
// Which mode each screen is.

/**
 * The mode each of the twenty nine is: the event map's value for its code, which is how the configuration names
 * a status screen and the only way the firmware would reach one. Refuses a configuration whose event map does
 * not hold exactly the thirty codes, or names one mode for two codes, since the template's screens would then
 * not be one to one with the configuration's.
 */
export function touchStatusScreenModes(c: Container): number[] {
  const map = eventMap(c);
  if (map === undefined) throw new ScreenRecordError('the configuration holds no event map');
  const keys = [...map.entries.keys()].sort((a, b) => a - b);
  if (keys.join() !== STATUS_CODES.join()) {
    throw new ScreenRecordError(`the event map names codes ${keys.join(', ')}, not 0 to ${STATUS_CODES.length - 1}`);
  }
  const modes = BUILT_CODES.map((code) => map.entries.get(code) as number);
  if (new Set([...modes, map.entries.get(DISPLAY_TEST_CODE)]).size !== STATUS_CODES.length) {
    throw new ScreenRecordError('the event map names one mode for two codes');
  }
  return modes;
}

// ---------------------------------------------------------------------------------------------------------
// The description, the builder and the check.

export type TouchStatusScreensSpec = TemplateScreensSpec<StatusScreenFont>;
export type TouchStatusScreensDescribed = TemplateScreensDescribed<StatusScreenFont>;

/**
 * Read off a configuration what a composer would supply for the twenty nine: `describeTemplateScreens` at the
 * modes the event map names. Refuses a screen whose tags, instructions, lists or programs are not the status
 * screen's shape, or a font that two places of one role disagree on. `layout` is `takeApart(c)`; `read` is where
 * every value is taken from, so a caller can blind every byte the description does not read.
 */
export function describeTouchStatusScreens(c: Container, layout: ContainerLayout, read?: ValueReader): TouchStatusScreensDescribed {
  return describeTemplateScreens(c, layout, SCREENS, touchStatusScreenModes(c), STATUS_SCREEN_FONTS, read);
}

export type BuiltTouchStatusScreens = BuiltTemplateScreens;

/** The screens built from a description, in mode order; everything but the description's numbers is generated. */
export function buildTouchStatusScreens(c: Container, spec: TouchStatusScreensSpec): BuiltTouchStatusScreens {
  return buildTemplateScreens(c, spec, SCREENS);
}

/** A layout with these screens swapped for the built ones, where the configuration's sat. */
export function withTouchStatusScreens(
  layout: ContainerLayout, built: BuiltTouchStatusScreens, place: TouchStatusScreensDescribed['place'],
): ContainerLayout {
  return withModeRecords(layout, built, place);
}

/** Describe, build and put back, and compare every byte with the configuration's. */
export function checkTouchStatusScreens(c: Container, read?: ValueReader): { screens: number; lists: number; described: number; structure: number } {
  const layout = takeApart(c);
  const described = describeTouchStatusScreens(c, layout, read);
  const built = buildTouchStatusScreens(c, described.spec);
  assertRebuilt(layOutContainer(withTouchStatusScreens(layout, built, described.place)).bytes, c, described.regions);
  return { screens: built.screens.length, lists: built.lists.size, described: described.described.size, structure: described.structure.size };
}
