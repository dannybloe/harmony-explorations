/** A refusal, named so a caller can tell a bad description from a bug. */
export class WiringError extends Error {}

/**
 * One instruction of a generated list, with what it names left symbolic.
 *
 * `call` names a list, `enter` a mode, `write` a state variable (`0x80 + v` with a constant value),
 * `map` a value map evaluated on a variable (`0x72`, map in the high byte), `select` a base slot 9 entry
 * (`0x1F 0xFF00 | entry`), `start` a timer (`0x1F 0xEB00 | timer`) and `queue` a base slot 11 screen
 * program (`0x73`), sections 73, 140, 280 and 369. A symbol is either generated by the family's builder or
 * the description's.
 */
export type WiringInstruction =
  | { readonly op: number; readonly operand: number }
  | { readonly call: string }
  | { readonly enter: string }
  | { readonly write: string; readonly value: number }
  | { readonly map: string; readonly on: string }
  | { readonly select: string }
  | { readonly start: string }
  /** `0x1F 0xEA00 | timer`, which the light lists send before starting a timer again; read as a stop. */
  | { readonly stop: string }
  /**
   * `0x71 form | variable`, a comparison of a variable the description names with the byte register,
   * section 140: `form` is the operand's high byte, bit 15 the else arm and bits 8 to 11 the operation.
   * A comparison of one of the firmware's own variables, 0 to 17, is written with `op` instead.
   */
  | { readonly test: string; readonly form: number }
  /** `0x73 program`, which queues a base slot 11 screen program by its entry, section 369. */
  | { readonly queue: string };

/** A device's own timer, carried whole, and the index it has in the table. */
export interface DeviceTimer {
  at: number;
  duration: number;
  instruction: { opcode: number; operand: number };
}

export interface BuiltWiring {
  logArea: ContainerPiece;
  eventMap: ContainerPiece;
  leadingList: ContainerPiece;
  parameterTable: ContainerPiece;
  parameterGroups: ContainerPiece[];
  timerTable: ContainerPiece;
  timerRecords: ContainerPiece[];
  /** Base slot 9 index to the entry built for it: the fixed ones and the leftover entry. */
  entries: Map<number, ContainerPiece>;
  /** Base slot 10 index to the list built for it. */
  lists: Map<number, ContainerPiece>;
  /** Base slot 10 index to the name the catalogue gives the list built there, for a caller that reports. */
  listNames: Map<number, string>;
  /** How many lists the front holds, the run of lists whose indices the family's builder generates. */
  frontLength: number;
  /**
   * Per built piece, the byte offsets that came from the description or a setting rather than from the
   * generator. Everything else in a piece is the generator's, which is what the blind control tests.
   */
  described: Map<ContainerPiece, number[]>;
}

/** A base slot 9 entry as a catalogue states it. */
export interface EntryTemplate {
  /** Base slot 9 index, or the entry symbol it is found under. */
  index: number | string;
  wide: boolean;
  bindings: Map<number, WiringInstruction>;
  /** The measured order of the tags that share a slot, first stored first. */
  ties: ReadonlyMap<string, readonly [number, number]>;
  /** Per tag, the flags byte of a wide entry where it is not `WIDE_FLAGS`. */
  flags?: ReadonlyMap<number, number>;
}

/** Two tags sharing a slot, in the order they are stored, as an `EntryTemplate`'s ties take them. */
export const tie = (a: number, b: number): [string, readonly [number, number]] =>
  [[a, b].sort((x, y) => x - y).join(','), [a, b]];

export type SymbolKind = 'lists' | 'modes' | 'variables' | 'maps' | 'entries' | 'timers' | 'programs';
export const SYMBOL_KINDS: readonly SymbolKind[] = ['lists', 'modes', 'variables', 'maps', 'entries', 'timers', 'programs'];
/** A kind's name for one symbol, for a refusal's message. */
export const ONE: Readonly<Record<SymbolKind, string>> = {
  lists: 'list', modes: 'mode', variables: 'variable', maps: 'map', entries: 'entry', timers: 'timer', programs: 'program',
};
export type Symbols = Record<SymbolKind, Map<string, number>>;
export const emptySymbols = (): Symbols => ({
  lists: new Map(), modes: new Map(), variables: new Map(), maps: new Map(), entries: new Map(), timers: new Map(), programs: new Map(),
});

/** The symbols an instruction names, with their kind. */
export function namedBy(ins: WiringInstruction): [SymbolKind, string][] {
  if ('call' in ins) return [['lists', ins.call]];
  if ('enter' in ins) return [['modes', ins.enter]];
  if ('write' in ins) return [['variables', ins.write]];
  if ('map' in ins) return [['maps', ins.map], ['variables', ins.on]];
  if ('select' in ins) return [['entries', ins.select]];
  if ('start' in ins) return [['timers', ins.start]];
  if ('stop' in ins) return [['timers', ins.stop]];
  if ('test' in ins) return [['variables', ins.test]];
  if ('queue' in ins) return [['programs', ins.queue]];
  return [];
}

export function lookup(symbols: Symbols, kind: SymbolKind, name: string): number {
  const value = symbols[kind].get(name);
  if (value === undefined) throw new WiringError(`the description names no ${ONE[kind]} ${JSON.stringify(name)}`);
  return value;
}

export function checkRange(what: string, value: number, max: number): number {
  if (!Number.isInteger(value) || value < 0 || value > max) throw new WiringError(`${what} ${value} is outside 0 to ${max}`);
  return value;
}

/**
 * An instruction's operand and opcode, and which of its three bytes the description decided: the
 * operand of a call, an enter, a map, a select, a start, a stop or a queue when its symbol is not
 * generated, the opcode of a write. Offsets are 0 and 1 for the operand and 2 for the opcode.
 */
export function encode(ins: WiringInstruction, symbols: Symbols, generated: Symbols): { operand: number; opcode: number; described: number[] } {
  const isGenerated = (kind: SymbolKind, name: string): boolean => generated[kind].has(name);
  if ('op' in ins) return { operand: ins.operand, opcode: ins.op, described: [] };
  if ('call' in ins) {
    return { operand: checkRange('a list index', lookup(symbols, 'lists', ins.call), 0xffff), opcode: 0x7f, described: isGenerated('lists', ins.call) ? [] : [0, 1] };
  }
  if ('enter' in ins) {
    return { operand: checkRange('a mode', lookup(symbols, 'modes', ins.enter), 0xffff), opcode: 0x7e, described: isGenerated('modes', ins.enter) ? [] : [0, 1] };
  }
  if ('write' in ins) {
    const v = checkRange('a written variable', lookup(symbols, 'variables', ins.write), 0x7f);
    return { operand: ins.value, opcode: 0x80 + v, described: [2] };
  }
  if ('map' in ins) {
    const m = checkRange('a value map', lookup(symbols, 'maps', ins.map), 0xff);
    const v = checkRange('a mapped variable', lookup(symbols, 'variables', ins.on), 0xff);
    return { operand: (m << 8) | v, opcode: 0x72, described: [0, 1] };
  }
  if ('select' in ins) {
    return { operand: 0xff00 | checkRange('an entry', lookup(symbols, 'entries', ins.select), 0xff), opcode: 0x1f, described: [0] };
  }
  if ('test' in ins) {
    const v = checkRange('a compared variable', lookup(symbols, 'variables', ins.test), 0xff);
    return { operand: ins.form | v, opcode: 0x71, described: [0] };
  }
  if ('queue' in ins) {
    return { operand: checkRange('a screen program', lookup(symbols, 'programs', ins.queue), 0xffff), opcode: 0x73, described: isGenerated('programs', ins.queue) ? [] : [0, 1] };
  }
  const timer = 'stop' in ins ? ins.stop : ins.start;
  const band = 'stop' in ins ? 0xea00 : 0xeb00;
  return { operand: band | checkRange('a timer', lookup(symbols, 'timers', timer), 0xff), opcode: 0x1f, described: isGenerated('timers', timer) ? [] : [0] };
}

/** Read a template's symbols off the instruction it was encoded as, and only those bytes. */
export function decode(ins: WiringInstruction, operand: number, opcode: number, symbols: Symbols, generated: Symbols): void {
  const take = (kind: SymbolKind, name: string, value: number): void => {
    if (generated[kind].has(name)) return;
    const had = symbols[kind].get(name);
    if (had !== undefined && had !== value) {
      throw new WiringError(`${ONE[kind]} ${JSON.stringify(name)} is ${had} in one place and ${value} in another`);
    }
    symbols[kind].set(name, value);
  };
  if ('call' in ins) take('lists', ins.call, operand);
  else if ('enter' in ins) take('modes', ins.enter, operand);
  else if ('write' in ins) take('variables', ins.write, opcode - 0x80);
  else if ('map' in ins) { take('maps', ins.map, operand >>> 8); take('variables', ins.on, operand & 0xff); }
  else if ('select' in ins) take('entries', ins.select, operand & 0xff);
  else if ('test' in ins) take('variables', ins.test, operand & 0xff);
  else if ('queue' in ins) take('programs', ins.queue, operand);
  else if ('start' in ins) take('timers', ins.start, operand & 0xff);
  else if ('stop' in ins) take('timers', ins.stop, operand & 0xff);
}

export const piece = (bytes: Uint8Array, owner: string, refs: PieceRef[] = []): ContainerPiece => ({ bytes, refs, owner });

/** An action list: `u8 count` then `{u16 operand; u8 opcode}`, section 26. */
export function encodeList(body: readonly WiringInstruction[], symbols: Symbols, generated: Symbols): { bytes: Uint8Array; described: number[] } {
  if (body.length > 0xff) throw new WiringError(`a list of ${body.length} instructions is more than its count holds`);
  const described: number[] = [];
  const instructions = body.map((ins, k) => {
    const e = encode(ins, symbols, generated);
    for (const at of e.described) described.push(1 + 3 * k + at);
    return { operand: e.operand, opcode: e.opcode };
  });
  return { bytes: actionListBytes(instructions), described };
}

/** The flags byte of a wide entry where a template states none. */
export const WIDE_FLAGS = 1;

/** A tagged list in either form, section 52, its tags in the slot order with the template's ties. */
export function encodeEntry(template: EntryTemplate, symbols: Symbols, generated: Symbols): { bytes: Uint8Array; described: number[] } {
  const order = orderOf(template);
  const stride = template.wide ? 5 : 4;
  const head = template.wide ? 2 : 1;
  const out = new Writer(head + stride * order.length);
  if (template.wide) out.u8(0).u8(order.length);
  else out.u8(order.length);
  const described: number[] = [];
  order.forEach((tag, k) => {
    if (template.wide) out.u8(template.flags?.get(tag) ?? WIDE_FLAGS);
    out.u8(tag);
    const e = encode(template.bindings.get(tag)!, symbols, generated);
    out.u16(e.operand).u8(e.opcode);
    for (const at of e.described) described.push(head + stride * k + stride - 3 + at);
  });
  return { bytes: out.bytes, described };
}

/** Read an entry's symbols back off its bytes, in the order `encodeEntry` stores it. */
export function decodeEntry(template: EntryTemplate, bytes: Uint8Array, symbols: Symbols, generated: Symbols): void {
  const stride = template.wide ? 5 : 4;
  const head = template.wide ? 2 : 1;
  orderOf(template).forEach((tag, k) => {
    const at = head + stride * k + stride - 3;
    decode(template.bindings.get(tag)!, u16(bytes, at), u8(bytes, at + 2), symbols, generated);
  });
}

/** Read a list's symbols back off its bytes. */
export function decodeList(body: readonly WiringInstruction[], bytes: Uint8Array, symbols: Symbols, generated: Symbols): void {
  body.forEach((ins, k) => {
    const at = 1 + 3 * k;
    decode(ins, u16(bytes, at), u8(bytes, at + 2), symbols, generated);
  });
}

export function orderOf(template: EntryTemplate): number[] {
  try {
    return tagSlotOrder([...template.bindings.keys()], template.ties);
  } catch (error) {
    if (error instanceof RangeError) throw new WiringError(error.message);
    throw error;
  }
}

/**
 * One action list written as text, the form a catalogue holds its lists in: instructions separated by
 * `|`, each `call L`, `enter M`, `V := n`, `map M on V`, `test V FF` (the form's high byte in hex),
 * `select E`, `start T`, `stop T`, `queue P`, or an opcode and operand in hex, `1F FB01`, for one that
 * names nothing a description supplies. Refuses anything else, so a catalogue cannot hold a misspelling.
 */
export function wiringList(text: string): WiringInstruction[] {
  if (text.trim() === '') return [];
  return text.split('|').map((part) => {
    const words = part.trim().split(/\s+/);
    const [first, second, third, fourth] = words;
    if (words.length === 2 && first === 'call') return { call: second! };
    if (words.length === 2 && first === 'enter') return { enter: second! };
    if (words.length === 2 && first === 'select') return { select: second! };
    if (words.length === 2 && first === 'start') return { start: second! };
    if (words.length === 2 && first === 'stop') return { stop: second! };
    if (words.length === 2 && first === 'queue') return { queue: second! };
    if (words.length === 3 && first === 'test' && /^[0-9A-F]{2}$/.test(third!)) return { test: second!, form: parseInt(third!, 16) << 8 };
    if (words.length === 3 && second === ':=' && /^\d+$/.test(third!)) return { write: first!, value: Number(third) };
    if (words.length === 4 && first === 'map' && third === 'on') return { map: second!, on: fourth! };
    if (words.length === 2 && /^[0-9A-F]{2}$/.test(first!) && /^[0-9A-F]{4}$/.test(second!)) return { op: parseInt(first!, 16), operand: parseInt(second!, 16) };
    throw new WiringError(`${JSON.stringify(part.trim())} is not an instruction a catalogue can state`);
  });
}

/**
 * Base slot 4, the event map: a fallback mode, then `count` status codes, code `k` to mode `base + k`, or
 * with no status screens carried every code to the fallback. The rule section 347 measured on the
 * Harmony 600, 650 and 700, and section 410 on the Harmony One, whose base is its ten firmware screens.
 */
export function buildEventMap(base: number, count: number, carried: boolean): Uint8Array {
  const event = new Writer(5 + 4 * count).u24(base).u16(count);
  for (let k = 0; k < count; k += 1) event.u8(k).u24(carried ? base + k : base);
  return event.bytes;
}

// ---------------------------------------------------------------------------------------------------
// Reading a laid out container's tables.
// ---------------------------------------------------------------------------------------------------

export function tablePiece(layout: ContainerLayout, slot: number): ContainerPiece {
  const head = layout.sections[slot]?.head;
  if (head === undefined || head.length !== 1) throw new WiringError(`base slot ${slot}'s table is not one piece`);
  return head[0]!;
}

/** The pieces a counted pointer table names, in table order. */
export function tableTargets(table: ContainerPiece): ContainerPiece[] {
  return [...table.refs].sort((a, b) => a.at - b.at).map((ref, k) => {
    if (!('to' in ref) || ref.offset !== 0) throw new WiringError(`entry ${k} of a table is not a piece of its own`);
    return ref.to;
  });
}

