def directory():
    """Where the vectors live, or None when there is no lab directory at all."""
    return os.path.join(lab.LAB, 'golden') if lab.LAB else None


def vector_path(name):
    d = directory()
    return None if d is None else os.path.join(d, '%s.json' % name)


def generate(name):
    """The vector for one sample, or None when its image is not available.

    Parses the file exactly as it sits on disk, rather than unwrapping an EZHex header first.
    That is on purpose: it makes `blob_offset` and every `file_offset` part of the comparison,
    and confusing a blob offset with a file offset is a mistake that has already cost time here.
    """
    path = lab.path(name)
    if not path:
        return None
    with open(path, 'rb') as fh:
        return gspm.summary(gspm.parse(fh.read()))


def main():
    write = '--write' in sys.argv
    d = directory()
    if d is None:
        print('no lab directory found; set HARMONY_LAB', file=sys.stderr)
        return 2
    if write:
        os.makedirs(d, exist_ok=True)

    missing, written, same, differ = [], [], [], []
    for name in CONTAINERS:
        current = generate(name)
        if current is None:
            missing.append(name)
            continue
        path = vector_path(name)
        if write:
            with open(path, 'w') as fh:
                json.dump(current, fh, indent=2, sort_keys=True)
                fh.write('\n')
            written.append(name)
            continue
        if not os.path.exists(path):
            missing.append(name + ' (no vector)')
            continue
        with open(path) as fh:
            stored = json.load(fh)
        (same if stored == current else differ).append(name)

    for name in differ:
        print('DIFFERS: %s' % name)
    print('%s: %d written, %d match, %d differ, %d unavailable'
          % (d, len(written), len(same), len(differ), len(missing)))
    if missing:
        print('unavailable: %s' % ', '.join(missing))
    return 1 if differ else 0


if __name__ == '__main__':
    sys.exit(main())
