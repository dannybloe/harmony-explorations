#!/usr/bin/env python3
"""
Golden vectors: what the Python parser says about each sample, for the TypeScript port to match.

The port is only provably equivalent if both parsers read the same bytes and produce the same
answer. Two suites of tests that happen to agree do not establish that, because each was written
from the same understanding and can be wrong in the same way. A vector generated by one and
asserted by the other is a real comparison.

The vectors live in the lab directory rather than in the repository, and that is a policy
decision rather than a convenience: a vector states section addresses and sizes for somebody's
actual configuration, which is derived from a private dump. Publishing a checksum is fine,
publishing a structural map of a stranger's remote is not.

    tools/golden.py --write        generate or refresh every vector
    tools/golden.py               compare, and exit non zero on any difference

Both suites read the vectors and skip cleanly when they are absent, the same contract as every
other image-backed test here.
"""
